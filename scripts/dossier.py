def load(path):
    try:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        sys.exit(f"error: cannot read {path}: {exc}")


def check(spec):
    """Return (errors, warnings)."""
    errors, warnings = [], []
    for key in ("title", "question", "options", "criteria", "scores"):
        if key not in spec:
            errors.append(f"missing top-level field '{key}'")
    if errors:
        return errors, warnings
    opts = [o["id"] for o in spec["options"]]
    crits = [c["id"] for c in spec["criteria"]]
    gates = [g["id"] for g in spec.get("gates", [])]
    if len(opts) < 2:
        errors.append("need at least two options (include 'do nothing' if nothing else)")
    if len(set(opts)) != len(opts) or len(set(crits)) != len(crits):
        errors.append("option and criterion ids must be unique")
    total = sum(float(c.get("weight", 0)) for c in spec["criteria"])
    if abs(total - 100) > 0.01:
        errors.append(f"criterion weights must sum to 100 (now {total:g})")
    if not 3 <= len(crits) <= 7:
        warnings.append(f"{len(crits)} criteria; 3-7 keeps the matrix honest")
    for c in spec["criteria"]:
        if not c.get("anchors"):
            warnings.append(f"criterion '{c['id']}' has no score anchors (what 1 / 3 / 5 mean)")
    counts = {"M": 0, "E": 0, "J": 0}
    for o in opts:
        row = spec["scores"].get(o)
        if row is None:
            errors.append(f"option '{o}' has no scores")
            continue
        for c in crits:
            cell = row.get(c)
            if cell is None:
                errors.append(f"missing score {o}/{c}")
                continue
            s = cell.get("score")
            if not isinstance(s, (int, float)) or not 1 <= s <= 5:
                errors.append(f"score {o}/{c} must be a number from 1 to 5")
            ev = cell.get("evidence")
            if ev not in EVIDENCE:
                errors.append(f"score {o}/{c} needs evidence M, E or J")
            else:
                counts[ev] += 1
            for k in ("low", "high"):
                if k in cell and not 1 <= cell[k] <= 5:
                    errors.append(f"{k} for {o}/{c} must be 1-5")
    for o in spec["options"]:
        for g in o.get("gates", {}):
            if g not in gates:
                errors.append(f"option '{o['id']}' references unknown gate '{g}'")
    n = sum(counts.values())
    if n and counts["J"] / n > 0.5:
        warnings.append(f"{counts['J']}/{n} scores are pure judgment; find data for the heaviest criteria")
    if not any(o.get("id") in ("status-quo", "do-nothing", "wait") for o in spec["options"]):
        warnings.append("no status-quo / do-nothing / wait option; add one unless it is truly impossible")
    if spec.get("reversibility") == "one-way" and not spec.get("premortem"):
        warnings.append("one-way decision without a pre-mortem")
    if not spec.get("verdict", {}).get("tripwires"):
        warnings.append("verdict has no tripwires")
    return errors, warnings


def eligible(spec):
    out = []
    for o in spec["options"]:
        if all(o.get("gates", {}).get(g["id"], True) for g in spec.get("gates", [])):
            out.append(o["id"])
    return out


def totals(spec, weights, field="score", opts=None):
    opts = opts or eligible(spec)
    res = {}
    for o in opts:
        row = spec["scores"][o]
        res[o] = sum(weights[c] * row[c].get(field, row[c]["score"]) for c in weights) / 100.0
    return res


def ranking(spec, weights):
    t = totals(spec, weights)
    return sorted(t.items(), key=lambda kv: -kv[1])


def reweight(weights, cid, value):
    """Set one weight and rescale the others proportionally so the sum stays 100."""
    rest = sum(w for k, w in weights.items() if k != cid)
    out = {}
    for k, w in weights.items():
        if k == cid:
            out[k] = value
        elif rest == 0:
            out[k] = (100 - value) / (len(weights) - 1)
        else:
            out[k] = w * (100 - value) / rest
    return out


def flip_points(spec):
    base = {c["id"]: float(c["weight"]) for c in spec["criteria"]}
    rank = ranking(spec, base)
    if len(rank) < 2:
        return []
    winner = rank[0][0]
    found = []
    for cid, w0 in base.items():
        best = None
        for step in range(0, 101):
            w = float(step)
            r = ranking(spec, reweight(base, cid, w))
            if r[0][0] != winner:
                if best is None or abs(w - w0) < abs(best[0] - w0):
                    best = (w, r[0][0])
        if best:
            found.append({"criterion": cid, "from": w0, "to": best[0], "new_winner": best[1]})
    return found


def dominance(spec):
    crits = [c["id"] for c in spec["criteria"]]
    opts = eligible(spec)
    pairs = []
    for a in opts:
        for b in opts:
            if a == b:
                continue
            sa, sb = spec["scores"][a], spec["scores"][b]
            if all(sa[c]["score"] >= sb[c]["score"] for c in crits) and any(
                sa[c]["score"] > sb[c]["score"] for c in crits
            ):
                pairs.append((a, b))
    return pairs


def stress(spec):
    base = {c["id"]: float(c["weight"]) for c in spec["criteria"]}
    names = {o["id"]: o["name"] for o in spec["options"]}
    rank = ranking(spec, base)
    lines = ["Ranking (weighted, 1-5 scale):"]
    for i, (o, s) in enumerate(rank, 1):
        lines.append(f"  {i}. {names[o]:<32} {s:.2f}")
    out = [o["id"] for o in spec["options"] if o["id"] not in eligible(spec)]
    if out:
        lines.append("Excluded by gates: " + ", ".join(names[o] for o in out))
    dom = dominance(spec)
    if dom:
        lines.append("Dominance:")
        for a, b in dom:
            lines.append(f"  {names[a]} dominates {names[b]}")
    fl = flip_points(spec)
    lines.append("Flip points:")
    if not fl:
        lines.append("  none: no single weight change flips the winner")
    for f in fl:
        lines.append(
            f"  {f['criterion']}: {f['from']:g} -> {f['to']:g} makes {names[f['new_winner']]} win"
        )
    if len(rank) >= 2:
        lead, second = rank[0][0], rank[1][0]
        worst = totals(spec, base, "low", [lead])[lead]
        best = totals(spec, base, "high", [second])[second]
        verdict = "holds" if worst > best else "does NOT hold"
        lines.append(
            f"Worst case for {names[lead]} ({worst:.2f}) vs best case for {names[second]} ({best:.2f}): lead {verdict}"
        )
    return "\n".join(lines)


def esc(x):
    return html.escape(str(x), quote=True)


