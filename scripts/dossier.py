def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=["check", "stress", "build"])
    ap.add_argument("spec")
    ap.add_argument("-o", "--out")
    a = ap.parse_args()
    spec = load(a.spec)
    errors, warnings = check(spec)
    for w in warnings:
        print(f"warning: {w}", file=sys.stderr)
    if errors:
        for e in errors:
            print(f"error: {e}", file=sys.stderr)
        sys.exit(1)
    if a.command == "check":
        print("ok" + (f" ({len(warnings)} warning(s))" if warnings else ""))
    elif a.command == "stress":
        print(stress(spec))
    else:
        out = Path(a.out or Path(a.spec).with_suffix(".html"))
